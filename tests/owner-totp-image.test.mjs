import test from 'node:test';
import assert from 'node:assert/strict';
import {ownerTotpImageSource} from '../src/continuity/owner-totp-image.mjs';
const svg='<svg xmlns="http://www.w3.org/2000/svg"><rect fill="#000"/></svg>';
test('official raw SVG and previously encoded SDK SVG display without URL fragments',()=>{
 for(const source of [svg,'<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n'+svg])for(const body of [source,encodeURIComponent(source)]){
  const result=ownerTotpImageSource('data:image/svg+xml;utf-8,'+body);
  assert.equal(decodeURIComponent(result.split(',')[1]),source);
  assert.equal(new URL(result).hash,'');
 }
});
test('bounded provider-sized QR output above the old 100KB limit is retained',()=>{
 const large='<svg xmlns="http://www.w3.org/2000/svg">'+'<rect width="1" height="1"/>'.repeat(5000)+'</svg>';
 assert.ok(large.length>100000);
 assert.equal(decodeURIComponent(ownerTotpImageSource('data:image/svg+xml;utf-8,'+large).split(',')[1]),large);
});
test('unknown formats, non-SVG responses and excessive output are rejected safely',()=>{
 for(const value of [null,'https://outside.invalid/image.svg','data:text/html,<svg/>','data:image/svg+xml;utf-8,<script>payload</script>','data:image/svg+xml;utf-8,%ZZ'])assert.throws(()=>ownerTotpImageSource(value),/^Error: MFA_QR_INVALID$/);
 assert.throws(()=>ownerTotpImageSource('data:image/svg+xml;utf-8,'+'x'.repeat(1000000)),/^Error: MFA_QR_TOO_LARGE$/);
});
