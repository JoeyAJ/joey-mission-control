export function localizeMessage(message,locale=current){
  if(typeof message!=='string')return message;
  for(const [pattern,key,params] of MESSAGE_PATTERNS){const match=message.match(pattern);if(match)return t(key,params?params(match,locale):{},locale);}
  return message;
}

// Static shell: elements declare data-i18n (text), data-i18n-aria-label (aria-label).
export function applyStaticTranslations(root=document,locale=current){
  for(const element of root.querySelectorAll('[data-i18n]'))element.textContent=t(element.dataset.i18n,{},locale);
  for(const element of root.querySelectorAll('[data-i18n-aria-label]'))element.setAttribute('aria-label',t(element.dataset.i18nAriaLabel,{},locale));
  if(root.documentElement)root.documentElement.lang=normalizeLocale(locale);
}
